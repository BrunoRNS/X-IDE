package org.xide.client.sockets;

import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.KeyStore;
import java.security.SecureRandom;
import java.security.cert.Certificate;
import java.security.cert.CertificateFactory;
import java.util.Objects;
import javax.net.ssl.SSLContext;
import javax.net.ssl.TrustManagerFactory;

/**
 * Builds client-side {@link SSLContext}s for {@code wss://} connections.
 *
 * <p>Used to trust the X-IDE edge certificate (a self-signed development
 * certificate by default) without disabling certificate validation.</p>
 */
public final class ClientSsl {

    private ClientSsl() {
    }

    /**
     * Returns an SSLContext that trusts only the PEM certificate(s) at the
     * given path: the development certificate generated by the infra stack or
     * a trusted certificate chain for real deployments.
     */
    public static SSLContext trustCertificate(Path certificatePem) {
        Objects.requireNonNull(certificatePem, "certificatePem");
        try (InputStream pem = Files.newInputStream(certificatePem)) {
            CertificateFactory certificateFactory = CertificateFactory.getInstance("X.509");
            KeyStore trustStore = KeyStore.getInstance(KeyStore.getDefaultType());
            trustStore.load(null, null);
            int index = 0;
            for (Certificate certificate : certificateFactory.generateCertificates(pem)) {
                trustStore.setCertificateEntry("xide-trusted-" + index++, certificate);
            }
            TrustManagerFactory trustManagerFactory =
                TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm());
            trustManagerFactory.init(trustStore);
            SSLContext sslContext = SSLContext.getInstance("TLS");
            sslContext.init(null, trustManagerFactory.getTrustManagers(), new SecureRandom());
            return sslContext;
        } catch (Exception e) {
            throw new IllegalArgumentException("Cannot load TLS certificate " + certificatePem, e);
        }
    }
}
